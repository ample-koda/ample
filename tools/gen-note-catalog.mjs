// Generates web/lib/note-catalog.mjs from spec/note-ops.json, so that the editor completion, the signature help and the typed spellings of the JavaScript evaluator
// read the very catalogue the C# checker reads. `node tools/gen-note-catalog.mjs` writes the file; `--check` fails when it is out of date (the web-lib tests run it).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'spec', 'note-ops.json'), 'utf8'));
const operators = {};
for (const op of spec.operators) {
  if (!op.returns) continue;
  operators[op.id] = { id: op.id, kind: op.kind, receiver: op.receiver ?? null, returns: op.returns, doc: op.doc ?? '', params: op.params };
}
const builtins = Object.fromEntries((spec.builtins ?? []).map((b) => [b.id, { id: b.id, kind: b.kind, receiver: b.receiver ?? null, returns: b.returns ?? '', doc: b.doc ?? '', params: b.params ?? [], ...(b.volatile ? { volatile: b.volatile } : {}) }]));
const text = `// GENERATED by tools/gen-note-catalog.mjs from spec/note-ops.json: do not edit by hand (docs/language/15-musical-types.md). @ample:note-catalog\n\nexport const NOTE_TYPES = ${JSON.stringify(spec.types, null, 2)};\n\nexport const NOTE_SIGNATURES = ${JSON.stringify(operators, null, 2)};\n\nexport const NOTE_BUILTINS = ${JSON.stringify(builtins, null, 2)};\n`;
const target = path.join(root, 'web', 'lib', 'note-catalog.mjs');
const csTarget = path.join(root, 'src', 'Ample.Language', 'NoteCatalogData.cs');
const json = fs.readFileSync(path.join(root, 'spec', 'note-ops.json'), 'utf8').trimEnd();
const cs = `// GENERATED by tools/gen-note-catalog.mjs from spec/note-ops.json: do not edit by hand. The language assembly may not depend on System.IO, so the catalogue is compiled in as text.\nnamespace Ample.Language;\n\ninternal static class NoteCatalogData\n{\n    internal const string Json = """""\n${json}\n""""";\n}\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text || !fs.existsSync(csTarget) || fs.readFileSync(csTarget, 'utf8') !== cs) { console.error('web/lib/note-catalog.mjs or src/Ample.Language/NoteCatalogData.cs is out of date: run node tools/gen-note-catalog.mjs'); process.exit(1); }
  console.log('note-catalog: ok');
} else {
  fs.writeFileSync(target, text);
  fs.writeFileSync(csTarget, cs);
  console.log('note-catalog: written');
}
