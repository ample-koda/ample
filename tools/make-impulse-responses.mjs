#!/usr/bin/env node
// Writes the "impulse-responses" audio pack: five synthetic, deterministic impulse responses (room, hall, plate, church, street) for the convolution block.
// They are made here from a seeded noise source, so they are CC0 (no recording, no author): file pack:impulse-responses/hall.
// Usage: node tools/make-impulse-responses.mjs [target-folder]   (default: <user ample home>/audio-packs/free/impulse-responses)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const RATE = 44100;
const target = process.argv[2] ?? path.join(process.env.AMPLE_HOME ?? path.join(process.env.LOCALAPPDATA ?? path.join(os.homedir(), '.local', 'share'), 'ample'), 'audio-packs', 'free', 'impulse-responses');

const presets = {
  room: { seed: 11, rt60: 0.45, pre: 4, bright: 0.55, early: [[7, 0.6], [11, 0.45], [17, 0.35], [23, 0.25], [31, 0.18]], note: 'a small furnished room' },
  hall: { seed: 23, rt60: 1.9, pre: 20, bright: 0.45, early: [[19, 0.5], [37, 0.4], [53, 0.3], [71, 0.25]], note: 'a concert hall' },
  plate: { seed: 37, rt60: 1.2, pre: 0, bright: 0.9, early: [], note: 'a bright plate: dense, no early reflections' },
  church: { seed: 41, rt60: 4.5, pre: 35, bright: 0.3, early: [[43, 0.45], [89, 0.35], [131, 0.3]], note: 'a stone church: long and dark' },
  street: { seed: 53, rt60: 0.7, pre: 6, bright: 0.6, early: [[95, 0.5], [190, 0.3], [310, 0.18]], note: 'a street between buildings: sparse slap echoes and a short tail' },
};

function noise(seed) {
  let s = seed >>> 0;
  return () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return (s / 4294967296) * 2 - 1; };
}

function make({ seed, rt60, pre, bright, early }) {
  const length = Math.round(RATE * rt60 * 1.15) + Math.round((pre / 1000) * RATE);
  const out = new Float64Array(length);
  const rand = noise(seed);
  let lp = 0;
  const start = Math.round((pre / 1000) * RATE);
  for (let i = start; i < length; i++) {
    const t = (i - start) / RATE;
    const decay = Math.exp((-6.91 * t) / rt60);
    const k = 0.05 + bright * 0.95 * Math.exp(-t / (rt60 * 0.6));   // the top end dies away first
    lp += k * (rand() - lp);
    out[i] = lp * decay;
  }
  for (const [ms, gain] of early) {
    const at = start + Math.round((ms / 1000) * RATE);
    if (at < length) out[at] += gain * (rand() > 0 ? 1 : -1);
  }
  out[start] += 1;   // the direct sound, so a mix of 100 % still has the attack
  const peak = out.reduce((m, v) => Math.max(m, Math.abs(v)), 0) || 1;
  return Int16Array.from(out, (v) => Math.max(-32768, Math.min(32767, Math.round((v / peak) * 29000))));
}

function wav(samples) {
  const data = Buffer.alloc(44 + samples.length * 2);
  data.write('RIFF', 0); data.writeUInt32LE(36 + samples.length * 2, 4); data.write('WAVEfmt ', 8);
  data.writeUInt32LE(16, 16); data.writeUInt16LE(1, 20); data.writeUInt16LE(1, 22); data.writeUInt32LE(RATE, 24); data.writeUInt32LE(RATE * 2, 28); data.writeUInt16LE(2, 32); data.writeUInt16LE(16, 34);
  data.write('data', 36); data.writeUInt32LE(samples.length * 2, 40);
  samples.forEach((v, i) => data.writeInt16LE(v, 44 + i * 2));
  return data;
}

fs.mkdirSync(target, { recursive: true });
for (const [name, preset] of Object.entries(presets)) fs.writeFileSync(path.join(target, `${name}.wav`), wav(make(preset)));
fs.writeFileSync(path.join(target, 'LICENSE.txt'), 'CC0 1.0 Universal (public domain dedication). These impulse responses are synthetic: generated by tools/make-impulse-responses.mjs from a seeded noise source, no recording involved.\n');
fs.writeFileSync(path.join(target, 'SOURCE.md'), `# Impulse responses (synthetic)\n\n- Made by: tools/make-impulse-responses.mjs (deterministic: same files every run)\n- Licence: CC0 1.0\n- Tier: free\n- Files: ${Object.entries(presets).map(([n, p]) => `${n}.wav (${p.note})`).join('; ')}\n- Use: convolution block, file pack:impulse-responses/<name>\n`);
console.log(`impulse-responses: ${Object.keys(presets).length} files in ${target}`);
