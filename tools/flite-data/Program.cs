using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using FliteData;

// Usage: dotnet run --project tools/flite-data -- <flite-source-folder> <repository-root> [--update-inputs] [--cg slt rms awb]
// With --cg only the clustergen voices that are named are converted (into src/Ample.Speech/Flite/Cg/Data, not embedded in the assembly); without it the four kal16 files are written.
// The source folder holds lang/ (cmu_us_kal16, cmulex, usenglish) and include/ of Flite at the pinned commit (copied; never committed).
const string Commit = "6c9f20dc915b17f5619340069889db0aa007fcdc";
const string Voice = "cmu_us_kal16";
if (args.Length < 2)
{
    Console.Error.WriteLine("Usage: flite-data <flite-source-folder> <repository-root> [--update-inputs]");
    return 2;
}

string source = Path.GetFullPath(args[0]), repo = Path.GetFullPath(args[1]);
bool update = args.Contains("--update-inputs");
if (args.Contains("--cg")) return CgMode.Run(source, repo, [.. args.SkipWhile(a => a != "--cg").Skip(1).TakeWhile(a => !a.StartsWith("--", StringComparison.Ordinal))], update);
string target = Path.Combine(repo, "src", "Ample.Speech", "Flite", "Data");
Directory.CreateDirectory(target);

(string File, List<KeyValuePair<string, byte[]>> Sections)[] outputs =
[
    ("flite-kal16-voice.bin", Extract.Voice(source)),
    ("flite-cmu-lexicon.bin", Extract.Lexicon(source)),
    ("flite-cmu-lts.bin", Extract.Lts(source)),
    ("flite-usenglish.bin", Extract.English(source))
];

string inputsFile = Path.Combine(repo, "tools", "flite-data", "inputs.sha256");
StringBuilder inputs = new();
foreach (string path in CSource.Used.Order(StringComparer.Ordinal))
{
    string relative = Path.GetRelativePath(source, path).Replace('\\', '/');
    inputs.Append(Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant()).Append("  ").Append(relative).Append('\n');
}

if (update)
{
    File.WriteAllText(inputsFile, inputs.ToString());
}
else if (File.ReadAllText(inputsFile).Replace("\r\n", "\n", StringComparison.Ordinal) != inputs.ToString())
{
    Console.Error.WriteLine("The source files are not the pinned ones (tools/flite-data/inputs.sha256). Use --update-inputs only for a deliberate new pin.");
    return 1;
}

using IncrementalHash all = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
foreach ((string file, List<KeyValuePair<string, byte[]>> sections) in outputs)
{
    byte[] bytes = Container.Write(sections);
    File.WriteAllBytes(Path.Combine(target, file), bytes);
    all.AppendData(bytes);
    Console.WriteLine($"{file}: {bytes.Length.ToString("N0", CultureInfo.InvariantCulture)} bytes ({Extract.Describe(sections)})");
}

string hash = Convert.ToHexString(all.GetHashAndReset()).ToLowerInvariant();
File.WriteAllText(
    Path.Combine(target, "FliteDataIdentity.g.cs"),
    $$"""
    // <auto-generated> by tools/flite-data: do not edit. </auto-generated>
    // Derived from Flite (Carnegie Mellon University), pinned source; the data tables are converted, not hand written.
    namespace Ample.Speech.Flite.Data;

    /// <summary>Which Flite source and which converted data this build of the engine stands on.</summary>
    public static class FliteDataIdentity
    {
        /// <summary>The commit of the Flite source the data was converted from.</summary>
        public const string SourceCommit = "{{Commit}}";

        /// <summary>The voice whose data is embedded.</summary>
        public const string VoiceName = "{{Voice}}";

        /// <summary>SHA-256 of the four embedded data files, in the order voice, lexicon, letter-to-sound, English.</summary>
        public const string DataSha256 = "{{hash}}";

        /// <summary>The identity string of takes made with this data (a changed value invalidates cached takes).</summary>
        public const string Value = "flite/{{Voice}}/{{Commit[..8]}}+{{hash[..16]}}";
    }

    """.Replace("\r\n", "\n", StringComparison.Ordinal));
Console.WriteLine($"identity flite/{Voice}/{Commit[..8]}+{hash[..16]}");
return 0;
