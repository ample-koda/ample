// Writes src/Ample.Speech/Flite/Cg/CgMathTables.cs from the table dump of plan/speech/flite/reference/cg/math (armdump.c compiled with the data files of
// ARM optimized-routines, commit 20859d3fd9e797dde592c489c8ef7d383f778620, MIT OR Apache-2.0 WITH LLVM-exception; the same tables and algorithms that glibc 2.28 and later use for exp and log).
// Usage: node tools/flite-data/gen-cg-math.mjs
import fs from 'node:fs';
const dump = fs.readFileSync('plan/speech/flite/reference/cg/math/arm-tables.txt', 'utf8').split('\n').filter(Boolean);
const scalar = {}, lists = {};
for (const line of dump) {
  const p = line.split(' ');
  if (p[0] === 'consts' || p[0] === 'HAVE_FAST_FMA') continue;
  if (p.length === 2) scalar[p[0]] = p[1];
  else (lists[p[0]] ??= []).push(p.slice(2));
}
const hex = (h) => `0x${h.toUpperCase()}UL`;
const list = (name, rows, take) => `    private static readonly ulong[] ${name} =\n    [\n${rows.map((r) => '        ' + take(r).map(hex).join(', ') + ',').join('\n')}\n    ];\n`;
let s = `// <auto-generated> by tools/flite-data/gen-cg-math.mjs: do not edit. </auto-generated>
// Port of ARM optimized-routines (commit 20859d3fd9e797dde592c489c8ef7d383f778620), math/exp_data.c and math/log_data.c. Translated to C# and modified: the tables are converted, not hand written.
// The tables of the exp and log functions of ARM optimized-routines (commit 20859d3fd9e797dde592c489c8ef7d383f778620; Copyright (c) 2018-2026 Arm Limited,
// SPDX-License-Identifier: MIT OR Apache-2.0 WITH LLVM-exception), which glibc 2.28 and later use: exp with 128 table entries and a polynomial of order 5, log with 128 table
// entries, polynomials of order 6 and 12 and the second table (chi, clo) of the build without fused multiply-add. Each value is the bit pattern of a double.
namespace Ample.Speech.Flite.Cg;

internal static partial class CgMath
{
    private const ulong ExpInvLn2N = ${hex(scalar['exp.invln2N'])};
    private const ulong ExpNegLn2HiN = ${hex(scalar['exp.negln2hiN'])};
    private const ulong ExpNegLn2LoN = ${hex(scalar['exp.negln2loN'])};
    private const ulong ExpShift = ${hex(scalar['exp.shift'])};
    private const ulong LogLn2Hi = ${hex(scalar['log.ln2hi'])};
    private const ulong LogLn2Lo = ${hex(scalar['log.ln2lo'])};

${list('ExpPolyBits', lists['exp.poly'], (r) => [r[0]])}
${list('ExpTableBits', lists['exp.tab'], (r) => [r[0]])}
${list('LogPolyBits', lists['log.poly'], (r) => [r[0]])}
${list('LogPoly1Bits', lists['log.poly1'], (r) => [r[0]])}
${list('LogTableBits', lists['log.tab'], (r) => [r[0], r[1]])}
${list('LogTable2Bits', lists['log.tab2'], (r) => [r[0], r[1]])}}
`;
// the poly/tab entries are "name index hex": the index is the first element after the name
s = s.replace(/\n\n\n/g, '\n\n');
fs.writeFileSync('src/Ample.Speech/Flite/Cg/CgMathTables.cs', s);
console.log('written', s.length);
