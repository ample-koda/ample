using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace FliteData;

/// <summary>The conversion of the clustergen voices: one .bin file per voice in src/Ample.Speech/Flite/Cg/Data, a pinned list of the source files per voice
/// (tools/flite-data/inputs-cg-VOICE.sha256) and a generated identity. The files are not embedded in the assembly: the voices are not shipped until their licence is confirmed.</summary>
internal static class CgMode
{
    private const string Commit = "6c9f20dc915b17f5619340069889db0aa007fcdc";

    public static int Run(string source, string repo, string[] voices, bool update)
    {
        if (voices.Length == 0)
        {
            Console.Error.WriteLine("Usage: flite-data <flite-source-folder> <repository-root> [--update-inputs] --cg slt [rms] [awb]");
            return 2;
        }

        string target = Path.Combine(repo, "src", "Ample.Speech", "Flite", "Cg", "Data");
        Directory.CreateDirectory(target);
        SortedDictionary<string, string> hashes = new(StringComparer.Ordinal);
        foreach (string voice in voices)
        {
            if (voice is not ("slt" or "rms" or "awb")) throw new ArgumentException($"Unknown voice '{voice}': slt, rms or awb.");
            CSource.Used.Clear();
            List<KeyValuePair<string, byte[]>> sections = ExtractCg.Voice(source, voice);
            StringBuilder inputs = new();
            foreach (string path in CSource.Used.Order(StringComparer.Ordinal))
            {
                string relative = Path.GetRelativePath(source, path).Replace('\\', '/');
                inputs.Append(Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant()).Append("  ").Append(relative).Append('\n');
            }

            string inputsFile = Path.Combine(repo, "tools", "flite-data", $"inputs-cg-{voice}.sha256");
            if (update)
            {
                File.WriteAllText(inputsFile, inputs.ToString());
            }
            else if (!File.Exists(inputsFile) || File.ReadAllText(inputsFile).Replace("\r\n", "\n", StringComparison.Ordinal) != inputs.ToString())
            {
                Console.Error.WriteLine($"The source files of {voice} are not the pinned ones ({inputsFile}). Use --update-inputs only for a deliberate new pin.");
                return 1;
            }

            byte[] bytes = Container.Write(sections);
            string file = $"flite-cg-{voice}.bin";
            File.WriteAllBytes(Path.Combine(target, file), bytes);
            hashes[voice] = Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();
            Console.WriteLine($"{file}: {bytes.Length.ToString("N0", CultureInfo.InvariantCulture)} bytes ({Extract.Describe(sections)})");
        }

        // the identity lists every voice that has a file in the folder, not only the ones of this run
        foreach (string file in Directory.GetFiles(target, "flite-cg-*.bin"))
        {
            string voice = Path.GetFileNameWithoutExtension(file)["flite-cg-".Length..];
            hashes[voice] = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(file))).ToLowerInvariant();
        }

        StringBuilder entries = new();
        foreach ((string voice, string hash) in hashes) entries.Append(CultureInfo.InvariantCulture, $"        [\"{voice}\"] = \"{hash}\",\n");
        File.WriteAllText(
            Path.Combine(target, "FliteCgDataIdentity.g.cs"),
            $$"""
            // <auto-generated> by tools/flite-data --cg: do not edit. </auto-generated>
            // Port of Flite (CMU, commit 6c9f20dc), the generated data of the clustergen voices. Translated to C# and modified: the data tables are converted, not hand written.
            namespace Ample.Speech.Flite.Cg;

            /// <summary>Which Flite source the converted clustergen voice data stands on, and the hash of each converted file.</summary>
            public static class FliteCgDataIdentity
            {
                /// <summary>The commit of the Flite source the data was converted from.</summary>
                public const string SourceCommit = "{{Commit}}";

                /// <summary>SHA-256 of the converted file of each voice (<c>flite-cg-VOICE.bin</c>).</summary>
                public static readonly IReadOnlyDictionary<string, string> Sha256 = new Dictionary<string, string>(StringComparer.Ordinal)
                {
            {{entries}}    };
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal));
        return 0;
    }
}
