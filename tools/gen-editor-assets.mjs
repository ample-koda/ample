// Generates the editor assets from spec/: the TextMate grammar and the snippets of the VS Code extension.
// Everything comes from the spec data (block types, keywords, classes, parameters); nothing is typed by hand.
// Run: node ample/tools/gen-editor-assets.mjs [--check]   (--check fails when the committed files are out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (...p) => JSON.parse(fs.readFileSync(path.join(root, ...p), 'utf8'));
const tokens = readJson('spec', 'tokens.json');
const classes = readJson('spec', 'classes.json').classes.map((c) => c.id);
const templates = fs.readdirSync(path.join(root, 'spec', 'templates')).filter((f) => f.endsWith('.json')).map((f) => readJson('spec', 'templates', f)).sort((a, b) => a.id.localeCompare(b.id));
const version = readJson('spec', 'version.json');

const alt = (list) => list.map((s) => s.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')).join('|');
const name = '"(?:[^"\\\\]|\\\\.)*"|[A-Za-z0-9_-]+';
const types = alt(templates.map((t) => t.id));
const headerWords = alt(tokens.keywords.filter((k) => ['at', 'for', 'as', 'bake', 'lock', 'refresh', 'freeze', 'seeds', 'plan'].includes(k)));
const topWords = alt(['composition', 'project', 'features', 'lint', 'assist']);

const grammar = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  name: 'AMPLE',
  scopeName: 'source.amplet',
  comment: `Generated by tools/gen-editor-assets.mjs from spec ${version.version || ''}. Do not edit by hand.`,
  fileTypes: ['amplet'],
  patterns: [{ include: '#comment' }, { include: '#view' }, { include: '#block' }, { include: '#layout' }, { include: '#directive' }],
  repository: {
    comment: { name: 'comment.line.number-sign.amplet', match: '#.*$' },
    string: { name: 'string.quoted.double.amplet', match: '"(?:[^"\\\\]|\\\\.)*"' },
    number: { name: 'constant.numeric.amplet', match: '-?\\b[0-9]+(?:\\.[0-9]+)?\\b' },
    classVersion: { match: `\\b(${alt(classes)})(@)([0-9]+(?:\\.[0-9]+)*)`, captures: { 1: { name: 'storage.type.class.amplet' }, 2: { name: 'punctuation.separator.amplet' }, 3: { name: 'constant.numeric.version.amplet' } } },
    headerKeyword: { name: 'keyword.control.amplet', match: `\\b(${headerWords})\\b` },
    directive: {
      match: `^(${topWords})\\b(.*)$`,
      name: 'meta.directive.amplet',
      captures: { 1: { name: 'keyword.control.directive.amplet' }, 2: { patterns: [{ include: '#inlineKeyword' }, { include: '#string' }, { include: '#number' }, { include: '#comment' }] } },
    },
    inlineKeyword: { name: 'keyword.other.amplet', match: `\\b(${alt(['tempo', 'master-seed', 'on', 'off', 'diff', 'button', 'auto'])})\\b` },
    view: {
      name: 'meta.view.amplet',
      begin: '^(view)\\s*(\\{)',
      beginCaptures: { 1: { name: 'keyword.control.directive.amplet' }, 2: { name: 'punctuation.definition.block.begin.amplet' } },
      end: '^(\\})',
      endCaptures: { 1: { name: 'punctuation.definition.block.end.amplet' } },
      patterns: [
        { include: '#comment' },
        { match: '^\\s*(section|line|order|group|size|pin|member|title|label|x|y)\\b', captures: { 1: { name: 'keyword.control.directive.amplet' } } },
        { match: '\\b(at|for)\\b', name: 'keyword.other.amplet' },
        { include: '#string' },
        { include: '#number' },
      ],
    },
    layout: {
      match: `^(layout)\\s+(${name})\\s+(-?[0-9]+)\\s+(-?[0-9]+)`,
      captures: { 1: { name: 'keyword.control.directive.amplet' }, 2: { name: 'variable.other.declaration.amplet' }, 3: { name: 'constant.numeric.amplet' }, 4: { name: 'constant.numeric.amplet' } },
    },
    from: {
      match: `^\\s*(from)\\s+(${name})(\\.)(${name})\\s*(->)\\s*(${name})`,
      captures: { 1: { name: 'keyword.control.from.amplet' }, 2: { name: 'variable.other.block.amplet' }, 3: { name: 'punctuation.accessor.amplet' }, 4: { name: 'variable.other.property.amplet' }, 5: { name: 'keyword.operator.arrow.amplet' }, 6: { name: 'variable.parameter.amplet' } },
    },
    parameter: { match: '^\\s*([A-Za-z0-9_-]+)(?=\\s|$)', captures: { 1: { name: 'entity.other.attribute-name.parameter.amplet' } } },
    block: {
      name: 'meta.block.amplet',
      begin: `^(${types})\\s+(${name})([^{#\\n]*)(\\{)`,
      beginCaptures: {
        1: { name: 'entity.name.type.block.amplet' },
        2: { name: 'variable.other.declaration.amplet' },
        3: { patterns: [{ include: '#classVersion' }, { include: '#headerKeyword' }, { include: '#string' }, { include: '#number' }] },
        4: { name: 'punctuation.definition.block.begin.amplet' },
      },
      end: '^\\s*(\\})',
      endCaptures: { 1: { name: 'punctuation.definition.block.end.amplet' } },
      patterns: [{ include: '#comment' }, { include: '#from' }, { include: '#parameter' }, { include: '#string' }, { include: '#number' }],
    },
  },
};

const snippets = Object.fromEntries(templates.map((t) => {
  const params = t.parameters.map((p, i) => `  ${p.name} \${${i + 2}:${String(p.default).replace(/[\\$}]/g, '\\$&')}}`);
  return [t.title || t.id, { prefix: [t.id], description: t.description || t.title, body: [`${t.id} \${1:${t.id}} {`, ...params, '}', '$0'] }];
}));

const outputs = [
  [path.join(root, 'editors', 'vscode', 'syntaxes', 'amplet.tmLanguage.json'), grammar],
  [path.join(root, 'editors', 'vscode', 'snippets', 'amplet.code-snippets'), snippets],
];

const check = process.argv.includes('--check');
let bad = 0;
for (const [file, data] of outputs) {
  const text = `${JSON.stringify(data, null, 2)}\n`;
  if (check) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (have !== text) { console.error(`${path.relative(root, file)} is out of date; run node ample/tools/gen-editor-assets.mjs`); bad++; }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(root, file)}`);
  }
}
process.exit(bad ? 1 : 0);
