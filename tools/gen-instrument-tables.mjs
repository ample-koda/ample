// Generates src/Ample.Audio/Instruments/InstrumentTables.g.cs: 2^(i/1200) as Q16 integers for i in 0..1199.
// Run once (and when the table design changes): node ample/tools/gen-instrument-tables.mjs
// Floating point is used HERE only, never at run time. The output is checked in and its SHA-256 is pinned by a test.
// Pass --check to verify the checked-in file instead of writing it.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'Ample.Audio', 'Instruments', 'InstrumentTables.g.cs');

const values = [];
for (let i = 0; i < 1200; i++) values.push(Math.round(Math.pow(2, i / 1200) * 65536));

const bytes = Buffer.alloc(values.length * 4);
values.forEach((v, i) => bytes.writeInt32LE(v, i * 4));
const hash = createHash('sha256').update(bytes).digest('hex');

const rows = [];
for (let i = 0; i < values.length; i += 12) rows.push('        ' + values.slice(i, i + 12).join(', ') + ',');
const text = `// <auto-generated> by ample/tools/gen-instrument-tables.mjs; do not edit. </auto-generated>
namespace Ample.Audio.Instruments;

/// <summary>Generated integer tables. Table hash: ${hash}.</summary>
internal static partial class InstrumentTables
{
    /// <summary>SHA-256 of the table as little-endian Int32 values, pinned by a test.</summary>
    public const string CentsQ16Sha256 = "${hash}";

    /// <summary>2^(i/1200) in Q16 (65536 = 1.0) for i in 0..1199: one octave in cents.</summary>
    public static readonly int[] CentsQ16 =
    [
${rows.join('\n')}
    ];
}
`;

if (process.argv.includes('--check')) {
  const have = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  if (have !== text) { console.error('InstrumentTables.g.cs is out of date'); process.exit(1); }
  console.log('ok ' + hash);
} else {
  writeFileSync(out, text);
  console.log('wrote ' + out + ' ' + hash);
}
